-- Baseline definition for audit_log (vbsec/PYA audit 2026-11-11, medium).
--
-- lib/audit.ts has written to this table since it was introduced, but no
-- migration in the repo defined it. This records the live shape (verified
-- against production on 2026-11-11: RLS enabled, zero policies) so a fresh
-- environment matches. `if not exists` throughout: it changes nothing on a
-- database that already has the table.
--
-- Append-only audit trail with no raw PII (emails and IPs are salted SHA-256
-- hashes), so service-role-only access is correct and there are deliberately
-- no RLS policies for any other role.
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  event text not null,
  waitlist_id uuid references public.waitlist(id) on delete set null,
  email_hash text,
  ip_hash text,
  detail jsonb not null default '{}'::jsonb
);

create index if not exists audit_log_occurred_at_idx on public.audit_log (occurred_at);
create index if not exists audit_log_event_idx on public.audit_log (event);
create index if not exists audit_log_waitlist_idx on public.audit_log (waitlist_id);

alter table public.audit_log enable row level security;
